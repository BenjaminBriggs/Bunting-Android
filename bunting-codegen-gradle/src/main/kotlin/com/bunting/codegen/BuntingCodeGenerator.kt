package com.bunting.codegen

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.longOrNull
import java.time.Instant
import java.time.format.DateTimeParseException

/**
 * Pure string-template generator for strongly-typed Bunting flag accessors,
 * mirroring the Swift `bunting-codegen` executable rule-for-rule:
 *
 * - Only the FIRST `/` in a flag key creates a namespace; deeper segments are
 *   joined with `_` before camelCasing (`a/b/c` → namespace `a`, property `bC`).
 * - Single-segment keys become root-level extension properties on `Bunting`.
 * - Defaults come from the `development` environment.
 * - A whole-number default on a `double` flag is emitted as a Double literal.
 * - Archived flags are annotated `@Deprecated("Flag archived")`.
 * - NEVER fails: a missing or malformed seed produces a fallback file with only
 *   a comment header — string-based access always works.
 */
object BuntingCodeGenerator {

    private const val HEADER = "// Generated by the Bunting codegen Gradle plugin. Do not edit.\n"

    fun generate(seedJson: String?, packageName: String): String {
        if (seedJson == null) return fallback(packageName, "no seed config was found")
        val flags = try {
            val root = Json.parseToJsonElement(seedJson).jsonObject
            root["flags"]?.jsonObject ?: return fallback(packageName, "seed config has no flags object")
        } catch (_: Exception) {
            return fallback(packageName, "seed config could not be parsed")
        }

        val rootFlags = mutableListOf<FlagSpec>()
        val namespaces = sortedMapOf<String, MutableList<FlagSpec>>()
        for (key in flags.keys.sorted()) {
            val spec = parseFlag(key, flags[key]?.jsonObject ?: continue) ?: continue
            if (spec.namespace == null) rootFlags.add(spec) else {
                namespaces.getOrPut(spec.namespace) { mutableListOf() }.add(spec)
            }
        }

        val needsInstant = (rootFlags + namespaces.values.flatten()).any { it.type == "date" }
        return buildString {
            append(HEADER)
            append("@file:Suppress(\"unused\", \"DEPRECATION\")\n\n")
            append("package $packageName\n\n")
            append("import com.bunting.Bunting\n")
            append("import com.bunting.BuntingClient\n")
            if (needsInstant) append("import java.time.Instant\n")
            append('\n')
            for (spec in rootFlags) {
                append(renderRootProperty(spec))
                append('\n')
            }
            for ((namespace, specs) in namespaces) {
                append(renderNamespace(namespace, specs))
                append('\n')
            }
        }.trimEnd('\n') + "\n"
    }

    private data class FlagSpec(
        val key: String,
        val namespace: String?,
        val propertyName: String,
        val type: String,
        val description: String?,
        val deprecated: Boolean,
        val devDefault: JsonPrimitive?,
    )

    private fun parseFlag(key: String, flag: JsonObject): FlagSpec? {
        val type = (flag["type"] as? JsonPrimitive)?.content ?: return null
        val segments = key.split("/")
        val namespace = if (segments.size > 1) segments.first() else null
        val propertySource = if (segments.size > 1) segments.drop(1).joinToString("_") else key
        val development = flag["development"] as? JsonObject
        // Tolerate the legacy `defaultValue`/`defaultdefault` keys, like Swift's decoder.
        val devDefault = (development?.get("default")
            ?: development?.get("defaultValue")
            ?: development?.get("defaultdefault")) as? JsonPrimitive
        return FlagSpec(
            key = key,
            namespace = namespace,
            propertyName = camelCase(propertySource),
            type = type,
            description = (flag["description"] as? JsonPrimitive)?.takeIf { it.isString }?.content,
            deprecated = (flag["deprecated"] as? JsonPrimitive)?.booleanOrNull ?: false,
            devDefault = devDefault,
        )
    }

    private fun renderRootProperty(spec: FlagSpec, indent: String = "", receiver: String = "Bunting.", target: String = "Bunting.instance"): String =
        buildString {
            append(kdoc(spec, indent))
            if (spec.deprecated) append("$indent@Deprecated(\"Flag archived\")\n")
            append("${indent}public val ${receiver}${spec.propertyName}: ${kotlinType(spec)}\n")
            append("$indent    get() = ${accessorCall(spec, target)}\n")
        }

    private fun renderNamespace(namespace: String, specs: List<FlagSpec>): String = buildString {
        val className = camelCase(namespace).replaceFirstChar { it.uppercase() } + "Flags"
        append("public val Bunting.${camelCase(namespace)}: $className\n")
        append("    get() = $className(Bunting.instance)\n\n")
        append("public class $className internal constructor(private val bunting: BuntingClient) {\n")
        for ((index, spec) in specs.withIndex()) {
            if (index > 0) append('\n')
            append(kdoc(spec, "    "))
            if (spec.deprecated) append("    @Deprecated(\"Flag archived\")\n")
            append("    public val ${spec.propertyName}: ${kotlinType(spec)}\n")
            append("        get() = ${accessorCall(spec, "bunting")}\n")
        }
        append("}\n")
    }

    private fun kdoc(spec: FlagSpec, indent: String): String {
        val description = spec.description?.let { if (it.endsWith(".")) "$it " else "$it. " } ?: ""
        return "$indent/** ${description}Flag key: `${spec.key}`. Type: `${spec.type}`. */\n"
    }

    private fun kotlinType(spec: FlagSpec): String = when (spec.type) {
        "bool" -> "Boolean"
        "int" -> "Long"
        "double" -> "Double"
        "date" -> "Instant"
        "json" -> "ByteArray?"
        else -> "String"
    }

    private fun accessorCall(spec: FlagSpec, target: String): String {
        val key = spec.key
        return when (spec.type) {
            "bool" -> "$target.bool(\"$key\", ${spec.devDefault?.booleanOrNull ?: false})"
            "int" -> "$target.int(\"$key\", ${spec.devDefault?.longOrNull ?: 0L}L)"
            "double" -> "$target.double(\"$key\", ${doubleLiteral(spec.devDefault)})"
            "date" -> "$target.date(\"$key\", ${instantLiteral(spec.devDefault)})"
            "json" -> "$target.jsonData(\"$key\")"
            // Unknown types (and `string`) fall back to the string accessor.
            else -> "$target.string(\"$key\", ${stringLiteral(spec.devDefault)})"
        }
    }

    /** Whole-number int defaults on double flags become Double literals (`2` → `2.0`). */
    private fun doubleLiteral(default: JsonPrimitive?): String {
        val value = default?.doubleOrNull ?: 0.0
        return value.toString()
    }

    /** Date defaults are pinned to the seed's ISO-8601 instant; unparseable → Instant.EPOCH. */
    private fun instantLiteral(default: JsonPrimitive?): String {
        val raw = default?.takeIf { it.isString }?.content ?: return "Instant.EPOCH"
        return try {
            Instant.parse(raw)
            "Instant.parse(\"$raw\")"
        } catch (_: DateTimeParseException) {
            "Instant.EPOCH"
        }
    }

    private fun stringLiteral(default: JsonPrimitive?): String {
        val raw = default?.takeIf { it.isString }?.content ?: ""
        val escaped = raw
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        return "\"$escaped\""
    }

    /** Splits on non-alphanumerics, lowercases the first part, capitalizes the rest. */
    internal fun camelCase(source: String): String {
        val parts = source.split(Regex("[^A-Za-z0-9]+")).filter { it.isNotEmpty() }
        if (parts.isEmpty()) return source
        return parts.first().lowercase() + parts.drop(1).joinToString("") { part ->
            part.lowercase().replaceFirstChar { it.uppercase() }
        }
    }

    private fun fallback(packageName: String, reason: String): String = buildString {
        append(HEADER)
        append("// Fallback: $reason. String-based flag access still works;\n")
        append("// typed accessors will appear once a valid seed config is present.\n\n")
        append("package $packageName\n")
    }
}
