package com.bunting.codegen

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.jsonObject
import org.gradle.api.GradleException
import java.time.Instant
import java.time.OffsetDateTime
import java.time.format.DateTimeParseException

/**
 * Pure string-template generator for strongly-typed Bunting flag accessors,
 * mirroring the Swift `bunting-codegen` executable rule-for-rule:
 *
 * - Only the FIRST `/` in a flag key creates a namespace; deeper segments are
 *   joined with `_` before camelCasing (`a/b/c` → namespace `a`, property `bC`).
 * - Single-segment keys become root-level extension properties on `Bunting`.
 * - Defaults come from the `development` environment's `default`, read by the
 *   flag's declared `type` (never by JSON shape): bool = JSON boolean, int = JSON
 *   integer, double = any JSON number, string = verbatim string, date = ISO-8601
 *   string, json = JSON-encoded string.
 * - A flag with an unknown type or a development default that doesn't match its
 *   type is skipped (no accessor) with a warning; it never fails the build.
 * - Accessors read through the `Bunting` facade's default-returning methods, so
 *   they return the development default (never throw) before `configure` runs.
 * - Archived flags are annotated `@Deprecated("Flag archived")`.
 * - NEVER fails on seed content: a missing or malformed seed produces a fallback
 *   file with only a comment header, so string-based access always works. The one
 *   hard error is two flags mapping to the same Kotlin identifier.
 */
object BuntingCodeGenerator {

    private const val HEADER = "// Generated by the Bunting codegen Gradle plugin. Do not edit.\n"

    /** Kotlin hard keywords: legal as identifiers only inside backticks. */
    private val HARD_KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in",
        "interface", "is", "null", "object", "package", "return", "super", "this", "throw",
        "true", "try", "typealias", "typeof", "val", "var", "when", "while",
    )

    /** Member properties of `com.bunting.Bunting`: an extension with one of these names is shadowed and unreachable. */
    private val BUNTING_MEMBER_PROPERTIES = setOf("state", "instance", "isConfigured")

    private val JSON_INTEGER = Regex("-?(0|[1-9][0-9]*)")
    private val JSON_NUMBER = Regex("-?(0|[1-9][0-9]*)(\\.[0-9]+)?([eE][+-]?[0-9]+)?")

    /**
     * @param warn receives one human-readable message per skipped flag.
     * @throws GradleException when two flags map to the same generated identifier.
     */
    fun generate(seedJson: String?, packageName: String, warn: (String) -> Unit = {}): String {
        if (seedJson == null) return fallback(packageName, "no seed config was found")
        val flags = try {
            val root = Json.parseToJsonElement(seedJson).jsonObject
            root["flags"] as? JsonObject ?: return fallback(packageName, "seed config has no flags object")
        } catch (_: Exception) {
            return fallback(packageName, "seed config could not be parsed")
        }

        val specs = parseFlags(flags, warn).filter { spec ->
            val shadowed = spec.namespace == null && spec.propertyName in BUNTING_MEMBER_PROPERTIES ||
                spec.namespace != null && spec.namespaceName in BUNTING_MEMBER_PROPERTIES
            if (shadowed) {
                val name = if (spec.namespace == null) spec.propertyName else spec.namespaceName
                warn("skipped flag \"${spec.key}\": its accessor Bunting.$name would be hidden by the Bunting member of the same name")
            }
            shadowed == false
        }
        val rootFlags = specs.filter { it.namespace == null }
        val namespaces = specs.filter { it.namespace != null }.groupBy { it.namespace!! }.toSortedMap()
        checkCollisions(rootFlags, namespaces)

        val needsInstant = specs.any { it.kind == FlagKind.DATE }
        return buildString {
            append(HEADER)
            append("@file:Suppress(\"unused\", \"DEPRECATION\")\n\n")
            append("package $packageName\n\n")
            append("import com.bunting.Bunting\n")
            if (needsInstant) append("import java.time.Instant\n")
            append('\n')
            for (spec in rootFlags) {
                append(renderRootProperty(spec))
                append('\n')
            }
            for (specsInNamespace in namespaces.values) {
                append(renderNamespace(specsInNamespace))
                append('\n')
            }
        }.trimEnd('\n') + "\n"
    }

    /**
     * Applies the C1/C2 rules to every flag in [flags], returning the ones that get an
     * accessor (sorted by key) and reporting each skipped flag through [warn]. Shared
     * with [SeedValidator] so `fetchBuntingConfig` warns about exactly what codegen skips.
     */
    internal fun parseFlags(flags: JsonObject, warn: (String) -> Unit): List<FlagSpec> =
        flags.keys.sorted().mapNotNull { key -> parseFlag(key, flags.getValue(key), warn) }

    internal enum class FlagKind(val wireName: String, val kotlinType: String) {
        BOOL("bool", "Boolean"),
        INT("int", "Long"),
        DOUBLE("double", "Double"),
        STRING("string", "String"),
        DATE("date", "Instant"),
        JSON("json", "ByteArray?"),
    }

    internal data class FlagSpec(
        val key: String,
        /** The raw namespace segment, or null for a root-level flag. */
        val namespace: String?,
        /** The namespace's camelCased name (no backticks), or null for a root-level flag. */
        val namespaceName: String?,
        /** The property's camelCased name (no backticks). */
        val propertyName: String,
        val kind: FlagKind,
        val description: String?,
        val deprecated: Boolean,
        /** The development default as a Kotlin expression (unused for `json`). */
        val defaultLiteral: String,
    )

    private fun parseFlag(key: String, element: JsonElement, warn: (String) -> Unit): FlagSpec? {
        fun skip(reason: String): FlagSpec? {
            warn("skipped flag \"$key\": $reason")
            return null
        }

        val flag = element as? JsonObject ?: return skip("it is not a JSON object")
        val typeName = (flag["type"] as? JsonPrimitive)?.takeIf { it.isString }?.content
            ?: return skip("it has no type")
        val kind = FlagKind.entries.firstOrNull { it.wireName == typeName }
            ?: return skip("unknown type \"$typeName\"")
        val development = flag["development"] as? JsonObject
            ?: return skip("it has no development environment")
        val rawDefault = development["default"] ?: return skip("its development environment has no default")
        val defaultLiteral = defaultLiteral(kind, rawDefault)
            ?: return skip("development default $rawDefault does not match its type \"$typeName\"")

        val segments = key.split("/")
        val namespace = if (segments.size > 1) segments.first() else null
        val propertySource = if (segments.size > 1) segments.drop(1).joinToString("_") else key
        val namespaceName = namespace?.let { safeName(camelCase(it)) ?: return skip("its namespace has no letters or digits") }
        val propertyName = safeName(camelCase(propertySource)) ?: return skip("its name has no letters or digits")

        return FlagSpec(
            key = key,
            namespace = namespace,
            namespaceName = namespaceName,
            propertyName = propertyName,
            kind = kind,
            description = (flag["description"] as? JsonPrimitive)?.takeIf { it.isString }?.content,
            deprecated = (flag["deprecated"] as? JsonPrimitive)?.booleanOrNull ?: false,
            defaultLiteral = defaultLiteral,
        )
    }

    /** The C2 reading of [raw] for [kind] as a Kotlin expression, or null when it doesn't match. */
    internal fun defaultLiteral(kind: FlagKind, raw: JsonElement): String? {
        val primitive = raw as? JsonPrimitive ?: return null
        if (primitive is JsonNull) return null
        val content = primitive.content
        return when (kind) {
            FlagKind.BOOL -> content.takeIf { primitive.isString == false && (it == "true" || it == "false") }
            FlagKind.INT -> {
                if (primitive.isString || JSON_INTEGER.matches(content) == false) return null
                val value = content.toLongOrNull() ?: return null
                // `-9223372036854775808L` is not a valid Kotlin literal.
                if (value == Long.MIN_VALUE) "Long.MIN_VALUE" else "${value}L"
            }
            FlagKind.DOUBLE -> {
                if (primitive.isString || JSON_NUMBER.matches(content) == false) return null
                content.toDoubleOrNull()?.takeIf { it.isFinite() }?.toString()
            }
            FlagKind.STRING -> if (primitive.isString) stringLiteral(content) else null
            // Re-emitted in canonical UTC form so any java.time (incl. Android's) parses it.
            FlagKind.DATE -> if (primitive.isString) parseDate(content)?.let { "Instant.parse(${stringLiteral(it.toString())})" } else null
            // The json accessor takes no default; only the shape is checked.
            FlagKind.JSON -> if (primitive.isString) "" else null
        }
    }

    /** ISO-8601 date-time with an offset (`Z` or `±hh:mm`), with or without fractional seconds. */
    private fun parseDate(raw: String): Instant? = try {
        OffsetDateTime.parse(raw).toInstant()
    } catch (_: DateTimeParseException) {
        null
    }

    private fun checkCollisions(rootFlags: List<FlagSpec>, namespaces: Map<String, List<FlagSpec>>) {
        val rootScope = mutableMapOf<String, String>()
        fun claim(scope: MutableMap<String, String>, name: String, key: String, accessor: String) {
            val existing = scope.putIfAbsent(name, key) ?: return
            throw GradleException(
                "Bunting codegen: flag keys \"$existing\" and \"$key\" both map to the accessor $accessor. " +
                    "Rename one of the flags so their names differ in more than punctuation or case."
            )
        }
        for (spec in rootFlags) claim(rootScope, spec.propertyName, spec.key, "Bunting.${spec.propertyName}")
        for (specs in namespaces.values) {
            val name = specs.first().namespaceName!!
            claim(rootScope, name, specs.first().key, "Bunting.$name")
            val classScope = mutableMapOf<String, String>()
            for (spec in specs) claim(classScope, spec.propertyName, spec.key, "Bunting.$name.${spec.propertyName}")
        }
    }

    private fun renderRootProperty(spec: FlagSpec): String = buildString {
        append(kdoc(spec, ""))
        if (spec.deprecated) append("@Deprecated(\"Flag archived\")\n")
        append("public val Bunting.${identifier(spec.propertyName)}: ${spec.kind.kotlinType}\n")
        append("    get() = ${accessorCall(spec)}\n")
    }

    private fun renderNamespace(specs: List<FlagSpec>): String = buildString {
        val name = specs.first().namespaceName!!
        val className = name.replaceFirstChar { it.uppercase() } + "Flags"
        append("public val Bunting.${identifier(name)}: $className\n")
        append("    get() = $className()\n\n")
        append("public class $className internal constructor() {\n")
        for ((index, spec) in specs.withIndex()) {
            if (index > 0) append('\n')
            append(kdoc(spec, "    "))
            if (spec.deprecated) append("    @Deprecated(\"Flag archived\")\n")
            append("    public val ${identifier(spec.propertyName)}: ${spec.kind.kotlinType}\n")
            append("        get() = ${accessorCall(spec)}\n")
        }
        append("}\n")
    }

    private fun kdoc(spec: FlagSpec, indent: String): String {
        val description = spec.description?.let(::commentSafe)?.let { if (it.endsWith(".")) "$it " else "$it. " } ?: ""
        return "$indent/** ${description}Flag key: `${commentSafe(spec.key)}`. Type: `${spec.kind.wireName}`. */\n"
    }

    /** Through the facade's default-returning methods: never throws before `Bunting.configure`. */
    private fun accessorCall(spec: FlagSpec): String {
        val key = stringLiteral(spec.key)
        return when (spec.kind) {
            FlagKind.BOOL -> "Bunting.bool($key, ${spec.defaultLiteral})"
            FlagKind.INT -> "Bunting.int($key, ${spec.defaultLiteral})"
            FlagKind.DOUBLE -> "Bunting.double($key, ${spec.defaultLiteral})"
            FlagKind.STRING -> "Bunting.string($key, ${spec.defaultLiteral})"
            FlagKind.DATE -> "Bunting.date($key, ${spec.defaultLiteral})"
            FlagKind.JSON -> "Bunting.jsonData($key)"
        }
    }

    /** A Kotlin string literal for [raw]: escapes quotes, backslashes, templates and every control character. */
    internal fun stringLiteral(raw: String): String = buildString {
        append('"')
        for (c in raw) {
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '$' -> append("\\$")
                c == '\n' -> append("\\n")
                c == '\r' -> append("\\r")
                c == '\t' -> append("\\t")
                c < ' ' || c == '\u007F' || c == ' ' || c == ' ' || c.isSurrogate() ->
                    append("\\u").append(c.code.toString(16).padStart(4, '0'))
                else -> append(c)
            }
        }
        append('"')
    }

    /** Text safe inside a single-line KDoc: no line breaks, and no `*` `/` pair that opens or closes a comment. */
    internal fun commentSafe(text: String): String = text
        .replace(Regex("\\s*[\\r\\n\\u2028\\u2029]+\\s*"), " ")
        .replace("*/", "*&#47;")
        .replace("/*", "&#47;*")

    /** Splits on non-alphanumerics, lowercases the first part, capitalizes the rest. Empty when nothing usable remains. */
    internal fun camelCase(source: String): String {
        val parts = source.split(Regex("[^A-Za-z0-9]+")).filter { it.isNotEmpty() }
        if (parts.isEmpty()) return ""
        return parts.first().lowercase() + parts.drop(1).joinToString("") { part ->
            part.lowercase().replaceFirstChar { it.uppercase() }
        }
    }

    /** Prefixes a leading digit with `_`; null when [camel] is empty. */
    private fun safeName(camel: String): String? = when {
        camel.isEmpty() -> null
        camel.first().isDigit() -> "_$camel"
        else -> camel
    }

    /** Backticks a hard keyword so it is a legal identifier. */
    internal fun identifier(name: String): String = if (name in HARD_KEYWORDS) "`$name`" else name

    private fun fallback(packageName: String, reason: String): String = buildString {
        append(HEADER)
        append("// Fallback: $reason. String-based flag access still works;\n")
        append("// typed accessors will appear once a valid seed config is present.\n\n")
        append("package $packageName\n")
    }
}
